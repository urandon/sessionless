func preparedMeasureFixture(t *testing.T, body []byte) (domain.SessionEvent, *sessionmaterial.PreparedV1) {
	t.Helper()
	user := domain.UserID("private-user")
	hash := sha256.Sum256(body)
	event := domain.SessionEvent{ID: "private-event", TenantID: "private-tenant", SessionID: "private-session", Kind: domain.SessionEventUserMessage, AuthorUserID: &user, IdempotencyKey: "private-idempotency", Payload: domain.BlobRef{TenantID: "private-tenant", Key: "tenants/private-tenant/sessions/private-session/events/private-event/message.json", Size: int64(len(body)), SHA256: hex.EncodeToString(hash[:])}}
	p, err := sessionmaterial.PrepareV1(event, body, nil)
	if err != nil {
		t.Fatalf("prepare measure fixture: %v", err)
	}
	t.Cleanup(p.Release)
	event.Sequence = 19
	event.CreatedAt = time.Date(2026, 10, 11, 20, 1, 2, 123456789, time.UTC)
	return event, p
}

func TestPreparedMeasureActualFinalCodecLiteralAndReleasedLifetime(t *testing.T) {
	body := []byte(`{"version":1,"text":"hello"}`)
	event, p := preparedMeasureFixture(t, body)
	measure, err := sessioncontext.MeasurePreparedRecordV1(event, p)
	if err != nil || !measure.Matches(event) {
		t.Fatalf("final seq19 measure: %v", err)
	}
	record, ok := measure.Record()
	if !ok {
		t.Fatal("valid preparation lacked verified final record")
	}
	encoded, err := sessioncontext.EncodeRecord(event, body)
	if err != nil {
		t.Fatal(err)
	}
	// Literal source hash independently checked with shasum, not generated by
	// the production codec or the constructor being exercised.
	wantLine := `{"schema":"sessionless.context-event.v1","event":{"id":"private-event","tenant_id":"private-tenant","session_id":"private-session","sequence":19,"kind":"user_message","author_user_id":"private-user","idempotency_key":"private-idempotency","payload":{"tenant_id":"private-tenant","key":"tenants/private-tenant/sessions/private-session/events/private-event/message.json","size":28,"sha256":"ca499ff825a55abda0411f94dc8c9e7ec938c5d983667aabb5094413338e8344"},"created_at":"2026-10-11T20:01:02.123456789Z"},"payload":{"version":1,"text":"hello"}}` + "\n"
	if string(encoded) != wantLine {
		t.Fatalf("actual codec differs from literal final record: got=%q want=%q", encoded, wantLine)
	}
	if !bytes.HasSuffix(encoded, []byte("\n")) || bytes.HasSuffix(encoded, []byte("\n\n")) || !bytes.Contains(encoded, []byte(`"sequence":19`)) || !bytes.Contains(encoded, []byte(`"created_at":"2026-10-11T20:01:02.123456789Z"`)) {
		t.Fatalf("actual final codec metadata/newline differs: %q", encoded)
	}
	digest := sha256.Sum256(encoded)
	gotDigest, verified := record.Digest()
	gotBytes, verifiedBytes := record.EncodedBytes()
	if !verified || !verifiedBytes || gotDigest != hex.EncodeToString(digest[:]) || gotBytes != int64(len(encoded)) {
		t.Fatalf("not actual codec bytes: digest=%s bytes=%d expected=%d", gotDigest, gotBytes, len(encoded))
	}
	withoutNewline := sha256.Sum256(encoded[:len(encoded)-1])
	if gotDigest == hex.EncodeToString(withoutNewline[:]) {
		t.Fatal("record digest omitted JSONL newline")
	}
	m, ok := measure.SourceMeasures()
	if !ok || m != (sessionmaterial.MeasuresV1{Kind: domain.SessionEventUserMessage, PayloadBytes: uint64(len(body)), CodexCompatible: true, RenderedFrameBytes: uint64(len("[user]\nhello\n"))}) {
		t.Fatalf("wrong literal source/frame measures: %+v verified=%v", m, ok)
	}
	if _, err := sessioncontext.DecodeJSONL(encoded, event.TenantID, event.SessionID); err == nil {
		t.Fatal("single record N>1 loosened complete-history sequence rules")
	}
	p.Release()
	if !measure.Matches(event) {
		t.Fatal("payload-free final measure improperly retained preparation lifetime")
	}
	if next, err := sessioncontext.MeasurePreparedRecordV1(event, p); !errors.Is(err, sessioncontext.ErrRecordNotMeasurable) || next.Matches(event) {
		t.Fatalf("released preparation reused: %v", err)
	}
	for _, value := range []any{measure, &measure, record} {
		if data, err := json.Marshal(value); data != nil || err == nil {
			t.Fatalf("private measure serialized: %q %v", data, err)
		}
		for _, format := range []string{"%v", "%+v", "%#v", "%s", "%q", "%x", "%d"} {
			got := fmt.Sprintf(format, value)
			if strings.Contains(got, "private") || strings.Contains(got, "hello") || strings.Contains(got, gotDigest) {
				t.Fatalf("format=%s disclosed measure=%s", format, got)
			}
		}
	}
}

func TestPreparedMeasureExactFinalTimestampAndSourceSubstitution(t *testing.T) {
	event, p := preparedMeasureFixture(t, []byte(`{"version":1,"text":"hello"}`))
	measure, err := sessioncontext.MeasurePreparedRecordV1(event, p)
	if err != nil {
		t.Fatal(err)
	}
	for _, test := range []struct {
		name       string
		change     func(*domain.SessionEvent)
		canMeasure bool
		matches    bool
	}{
		{"same zero-offset location", func(e *domain.SessionEvent) { e.CreatedAt = e.CreatedAt.In(time.FixedZone("same offset", 0)) }, true, true},
		{"different serialized offset", func(e *domain.SessionEvent) { e.CreatedAt = e.CreatedAt.In(time.FixedZone("other offset", 3600)) }, true, false},
		{"nanosecond", func(e *domain.SessionEvent) { e.CreatedAt = e.CreatedAt.Add(time.Nanosecond) }, true, false},
		{"next sequence", func(e *domain.SessionEvent) { e.Sequence++ }, true, false},
		{"zero sequence", func(e *domain.SessionEvent) { e.Sequence = 0 }, false, false},
		{"zero time", func(e *domain.SessionEvent) { e.CreatedAt = time.Time{} }, false, false},
		{"event", func(e *domain.SessionEvent) { e.ID = "other-event" }, false, false},
		{"session", func(e *domain.SessionEvent) { e.SessionID = "other-session" }, false, false},
		{"tenant", func(e *domain.SessionEvent) { e.TenantID = "other-tenant" }, false, false},
		{"author", func(e *domain.SessionEvent) { v := domain.UserID("other-user"); e.AuthorUserID = &v }, false, false},
		{"idempotency", func(e *domain.SessionEvent) { e.IdempotencyKey = "other-idempotency" }, false, false},
		{"payload key", func(e *domain.SessionEvent) { e.Payload.Key += ".other" }, false, false},
		{"payload size", func(e *domain.SessionEvent) { e.Payload.Size++ }, false, false},
		{"payload digest", func(e *domain.SessionEvent) { e.Payload.SHA256 = strings.Repeat("a", 64) }, false, false},
	} {
		t.Run(test.name, func(t *testing.T) {
			changed := event
			test.change(&changed)
			if measure.Matches(changed) != test.matches {
				t.Fatalf("old measure Matches=%v want=%v", measure.Matches(changed), test.matches)
			}
			next, err := sessioncontext.MeasurePreparedRecordV1(changed, p)
			if test.canMeasure {
				if err != nil || !next.Matches(changed) {
					t.Fatalf("new final allocation denied: %v", err)
				}
				oldRecord, _ := measure.Record()
				newRecord, _ := next.Record()
				oldDigest, _ := oldRecord.Digest()
				newDigest, _ := newRecord.Digest()
				if (oldDigest == newDigest) != test.matches {
					t.Fatal("actual changed codec metadata reused digest")
				}
			} else if !errors.Is(err, sessioncontext.ErrRecordNotMeasurable) || next.Matches(changed) {
				t.Fatalf("source substitution measured: %v", err)
			}
		})
	}
}

func TestPreparedMeasureRoundTripUnknownIsNotRendererOrMeasuredZero(t *testing.T) {
	for _, test := range []struct {
		name, body string
		measurable bool
	}{
		{"compact", `{"version":1,"text":"hello"}`, true},
		{"whitespace", `{ "version":1, "text":"hello" }`, false},
		{"raw HTML escaping", `{"version":1,"text":"<private>"}`, false},
		{"already escaped", `{"version":1,"text":"\u003cprivate\u003e"}`, true},
	} {
		t.Run(test.name, func(t *testing.T) {
			e, p := preparedMeasureFixture(t, []byte(test.body))
			copy, source, err := p.CopyForFinalV1(e)
			clear(copy)
			if err != nil || !source.CodexCompatible {
				t.Fatalf("recognized renderable source fixture: %+v %v", source, err)
			}
			m, err := sessioncontext.MeasurePreparedRecordV1(e, p)
			if test.measurable {
				if err != nil || !m.Matches(e) {
					t.Fatalf("round-trip source denied: %v", err)
				}
			} else {
				if !errors.Is(err, sessioncontext.ErrRecordNotMeasurable) || err.Error() != "canonical record not measurable" || m.Matches(e) {
					t.Fatalf("non-round-trip source normalized or disclosed: %v", err)
				}
				if r, ok := m.Record(); ok {
					t.Fatalf("unknown returned record=%v", r)
				}
				if s, ok := m.SourceMeasures(); ok || s != (sessionmaterial.MeasuresV1{}) {
					t.Fatalf("unknown retained measured zero/source claims: %+v %v", s, ok)
				}
			}
		})
	}
	var zero sessioncontext.FinalMaterialMeasureV1
	e, _ := preparedMeasureFixture(t, []byte(`{"version":1,"text":"hello"}`))
	if zero.Matches(e) {
		t.Fatal("zero final measure verified")
	}
	for _, p := range []*sessionmaterial.PreparedV1{nil, new(sessionmaterial.PreparedV1)} {
		m, err := sessioncontext.MeasurePreparedRecordV1(e, p)
		if !errors.Is(err, sessioncontext.ErrRecordNotMeasurable) || m.Matches(e) {
			t.Fatalf("nil/zero preparation measured: %v", err)
		}
	}
}

func TestPreparedMeasureNonRenderingSchemasAndInputImmutability(t *testing.T) {
	for _, test := range []struct {
		kind domain.SessionEventKind
		body string
	}{
		{domain.SessionEventToolCall, `{"schema":"sessionless.tool-event.v1","call_id":"call","tool_name":"tool","content":{}}`},
		{domain.SessionEventToolResult, `{"schema":"sessionless.tool-event.v1","call_id":"call","tool_name":"tool","content":null}`},
		{domain.SessionEventSystemNotice, `{"schema":"sessionless.run-terminal-notice.v1","code":"failed","cancelled":false}`},
	} {
		t.Run(string(test.kind), func(t *testing.T) {
			body := []byte(test.body)
			event, unused := preparedMeasureFixture(t, []byte(`{"version":1,"text":"hello"}`))
			unused.Release()
			run := domain.RunID("private-run")
			event.Kind, event.RunID = test.kind, &run
			event.Payload.Size = int64(len(body))
			hash := sha256.Sum256(body)
			event.Payload.SHA256 = hex.EncodeToString(hash[:])
			prepared, err := sessionmaterial.PrepareV1(event, body, nil)
			if err != nil {
				t.Fatal(err)
			}
			t.Cleanup(prepared.Release)
			before := bytes.Clone(body)
			measure, err := sessioncontext.MeasurePreparedRecordV1(event, prepared)
			if err != nil || !measure.Matches(event) || !bytes.Equal(before, body) {
				t.Fatalf("non-rendering canonical source not measured or input mutated: %v", err)
			}
			m, ok := measure.SourceMeasures()
			if !ok || m.CodexCompatible || m.RenderedFrameBytes != 0 || m.PayloadBytes != uint64(len(body)) {
				t.Fatalf("measurable source falsely render-compatible: %+v %v", m, ok)
			}
			wantTool := uint64(0)
			if test.kind != domain.SessionEventSystemNotice {
				wantTool = uint64(len(body))
			}
			if m.ToolEnvelopeBytes != wantTool {
				t.Fatalf("tool-envelope bytes=%d want=%d", m.ToolEnvelopeBytes, wantTool)
			}
			*event.RunID = "caller-mutated-run"
			if measure.Matches(event) {
				t.Fatal("final measure retained caller RunID pointer")
			}
			run = "private-run"
			if !measure.Matches(event) {
				t.Fatal("final measure lost cloned source identity")
			}
		})
	}
}

func TestPreparedMeasureCannotBypassActualEncodedCeiling(t *testing.T) {
	// Recognized renderable source under the payload ceiling can still expand
	// when private reference metadata is JSON-escaped by the real codec.
	body := []byte(`{"version":1,"text":"` + strings.Repeat("a", sessionmaterial.MaxPayloadBytesV1-100) + `"}`)
	event, base := preparedMeasureFixture(t, body)
	base.Release()
	event.Payload.Key += strings.Repeat("<", 7000)
	p, err := sessionmaterial.PrepareV1(event, body, nil)
	if err != nil {
		t.Fatalf("bounded recognized source should prepare before actual encoding: %v", err)
	}
	t.Cleanup(p.Release)
	encoded, err := sessioncontext.EncodeRecord(event, body)
	if err != nil || len(encoded) <= sessioncontext.MaxMeasuredEncodedRecordBytesV1 {
		t.Fatalf("independent encoded-overflow fixture size=%d err=%v", len(encoded), err)
	}
	m, err := sessioncontext.MeasurePreparedRecordV1(event, p)
	if !errors.Is(err, sessioncontext.ErrRecordNotMeasurable) || m.Matches(event) {
		t.Fatalf("prepared source bypassed final encoded ceiling: %v", err)
	}
	if source, ok := m.SourceMeasures(); ok || source != (sessionmaterial.MeasuresV1{}) {
		t.Fatalf("failed final codec retained source claims: %+v %v", source, ok)
	}
}

func TestPreparedMeasureExactEncodedBoundaryPartition(t *testing.T) {
	const prefix, suffix = `{"version":1,"text":"`, `"}`
	for _, offset := range []int{-1, 0, 1} {
		t.Run(fmt.Sprintf("encoded/%+d", offset), func(t *testing.T) {
			body := []byte(prefix + "hello" + suffix)
			event, unused := preparedMeasureFixture(t, body)
			unused.Release()
			event.Payload.Key += strings.Repeat("<", 7000)
			base, err := sessioncontext.EncodeRecord(event, body)
			if err != nil {
				t.Fatal(err)
			}
			want := sessioncontext.MaxMeasuredEncodedRecordBytesV1 + offset
			size := want - len(base) + len(body)
			// Exactly two bounded encodings compensate for the changed decimal
			// size width; no approximation enters the assertion or product code.
			for range 2 {
				body = []byte(prefix + strings.Repeat("a", size-len(prefix)-len(suffix)) + suffix)
				hash := sha256.Sum256(body)
				event.Payload.Size, event.Payload.SHA256 = int64(len(body)), hex.EncodeToString(hash[:])
				encoded, err := sessioncontext.EncodeRecord(event, body)
				if err != nil {
					t.Fatal(err)
				}
				size += want - len(encoded)
			}
			encoded, err := sessioncontext.EncodeRecord(event, body)
			if err != nil || len(encoded) != want || len(body) > sessionmaterial.MaxPayloadBytesV1 {
				t.Fatalf("exact boundary fixture size=%d want=%d payload=%d err=%v", len(encoded), want, len(body), err)
			}
			prepared, err := sessionmaterial.PrepareV1(event, body, nil)
			if err != nil {
				t.Fatal(err)
			}
			t.Cleanup(prepared.Release)
			m, err := sessioncontext.MeasurePreparedRecordV1(event, prepared)
			if offset <= 0 {
				if err != nil || !m.Matches(event) {
					t.Fatalf("exact legal encoded boundary denied: %v", err)
				}
				r, _ := m.Record()
				size, ok := r.EncodedBytes()
				if !ok || size != int64(want) {
					t.Fatalf("measured bytes=%d verified=%v want=%d", size, ok, want)
				}
			} else if !errors.Is(err, sessioncontext.ErrRecordNotMeasurable) || m.Matches(event) {
				t.Fatalf("encoded ceiling+1 accepted: %v", err)
			}
		})
	}
}
