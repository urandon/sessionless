// OpenTerminalHistoryNativeV1 reuses the existing explicit disposable-loopback
// guard and DB lifetime. Schema/cutovers must already be established by the
// existing CI gate. No shared support import is allowed in this package: the
// external native test owns Ready/Offer/Claim on the returned original Store.
func OpenTerminalHistoryNativeV1(t *testing.T) (*Store, *sql.DB, context.Context, domain.TenantID) {
	t.Helper()
	f, ctx := nativeOwnedCurrentFixture(t)
	store, err := New(f.store.db, Options{})
	if err != nil {
		t.Fatal(err)
	}
	tenant := f.scope.tenant
	// This tenant is freshly generated by the original native fixture. Arm
	// cleanup BEFORE the first Ready write, including partial setup failures.
	t.Cleanup(func() {
		cleanup, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		for _, table := range []string{
			"attached_worker_output_receipts", "attached_worker_attempt_messages", "attached_worker_attempt_heads",
			"attached_worker_attempt_deadlines_v1", "attached_worker_control_messages", "attached_worker_presence_expiry_v1",
			"attached_worker_capability_manifests", "attached_worker_attach_challenges", "attached_worker_connections",
			"attached_worker_audit_events", "attached_worker_enrollments", "attached_workers",
			"audit_events", "run_finalizations", "run_explanation_heads_v1", "worker_jobs",
			"quota_expiry_v2", "quota_reservations", "subscription_scheduler_slots", "tenant_scheduler_counters",
			"dispatch_ready_v2", "dispatch_outbox", "artifact_manifests_by_run", "artifact_manifests",
			"lease_expiry_v2", "lease_heads", "leases", "attempts", "runs_by_session", "run_idempotency", "runs",
			"subscription_connections", "session_event_idempotency", "session_events",
			"session_material_boundaries_v1", "session_material_current_v1", "session_displays",
			"session_activity", "session_participants", "sessions", "tenant_memberships", "tenants", "telegram_updates",
		} {
			if _, err := store.db.ExecContext(cleanup, "DELETE FROM "+table+" WHERE tenant_id=$1", tenant); err != nil {
				t.Errorf("cleanup exact disposable AW07 tenant table=%s: %v", table, err)
			}
		}
	})
	return store, store.db, ctx, tenant
}

// TerminalHistoryNativeResultV1 is copied DATA from the actual historical
// classifier, never a capability, finalization approval or reconstructed owner.
type TerminalHistoryNativeResultV1 struct {
	Run             domain.Run
	Manifest        domain.ArtifactManifest
	Events          []domain.SessionEvent
	Marker          string
	NilEvidenceSeal string
	UsesEvidence    bool
}

type terminalNativeSnapshot struct {
	Run     domain.Run
	Session domain.Session
	Marker  string
	Events  []domain.SessionEvent
}

// ReadTerminalHistoryNativeV1 composes the EXISTING bounded metadata and V1
// material/manifest/classifier phases. It has no old Attempt/Job/lease input.
// This proves a historical reader, NOT a new LocalV1 Source/RunModelStep.
func ReadTerminalHistoryNativeV1(ctx context.Context, store *Store, tenant domain.TenantID, session domain.SessionID, run domain.RunID, blobs ports.BlobStore) (TerminalHistoryNativeResultV1, error) {
	var result TerminalHistoryNativeResultV1
	if ctx == nil || ctx.Err() != nil || store == nil || blobs == nil || tenant.Validate() != nil || session.Validate() != nil || run.Validate() != nil {
		return result, domain.ErrMembershipDenied
	}
	call, cancel := ownedAuthorityCallContext(ctx)
	defer cancel()
	var first terminalNativeSnapshot
	if err := store.ownedAuthorityTx(call, func(ctx context.Context, q *ownedAuthorityQuery) error {
		var err error
		first, err = readTerminalNativeSnapshot(ctx, q, tenant, session, run)
		return err
	}); err != nil {
		return result, err
	}
	var records []sessioncontext.EventPayload
	defer func() {
		for i := range records {
			clear(records[i].Payload)
		}
	}()
	for _, event := range first.Events {
		ref := event.Payload
		if ref.Validate() != nil || ref.TenantID != tenant || ref.Size <= 0 || ref.Size > 1<<20 || chargeOwnedAuthorityBody(call, uint64(ref.Size)+1) != nil {
			return result, domain.ErrMembershipDenied
		}
		r, err := blobs.Open(call, tenant, ref)
		if err != nil || r == nil {
			if r != nil {
				_ = r.Close()
			}
			return result, domain.ErrMembershipDenied
		}
		body, readErr := io.ReadAll(io.LimitReader(r, ref.Size+1))
		closeErr := r.Close()
		if readErr != nil || closeErr != nil || call.Err() != nil || !localRetainedBytes(ref, body) {
			clear(body)
			return result, domain.ErrMembershipDenied
		}
		records = append(records, sessioncontext.EventPayload{Event: event, Payload: body})
	}
	err := store.ownedAuthorityTx(call, func(ctx context.Context, q *ownedAuthorityQuery) error {
		current, err := readTerminalNativeSnapshot(ctx, q, tenant, session, run)
		if err != nil || !reflect.DeepEqual(current, first) {
			return q.budget.deny()
		}
		ids := []domain.RunID{run}
		runs := map[domain.RunID]domain.Run{run: current.Run}
		materials, err := prepareLocalTerminalLegacyMaterials(q, ids, map[domain.RunID][]sessioncontext.EventPayload{run: records}, runs, map[domain.RunID]string{run: current.Marker})
		if err != nil {
			return err
		}
		manifests, err := readLocalTerminalLegacyManifests(ctx, q, ids, materials, runs)
		if err != nil {
			return err
		}
		legacy, err := readLocalTerminalLegacySnapshot(ctx, q, current.Run, current.Marker, materials[run], manifests)
		if err != nil {
			return err
		}
		nilSeal, err := runFinalizationDigest(current.Run.Status, &legacy.Manifest, materials[run].Drafts, nil, nil)
		if err != nil {
			return err
		}
		result = TerminalHistoryNativeResultV1{Run: legacy.Run.Clone(), Manifest: legacy.Manifest, Events: append([]domain.SessionEvent(nil), current.Events...), Marker: current.Marker, NilEvidenceSeal: nilSeal, UsesEvidence: legacy.Head != nil || legacy.Effect != nil || legacy.Evidence != nil}
		return nil
	})
	if err != nil {
		return TerminalHistoryNativeResultV1{}, err
	}
	return result, nil
}

func readTerminalNativeSnapshot(ctx context.Context, q *ownedAuthorityQuery, tenant domain.TenantID, session domain.SessionID, run domain.RunID) (terminalNativeSnapshot, error) {
	var snapshot terminalNativeSnapshot
	rows, err := q.QueryContext(ctx, localTerminalHistoryRunsSQL(1), tenant, session, run, uint64(32769))
	if err != nil {
		return snapshot, err
	}
	var id, raw, status, marker string
	if !rows.Next() {
		rows.Close()
		return snapshot, q.budget.deny()
	}
	n, err := scanOwnedCurrentRow(rows, &id, &raw, &status, &marker)
	if err != nil || q.budget.materialized(q.callback, n) != nil || rows.Next() || rows.Err() != nil || rows.Close() != nil || len(raw) > 32768 || len(id) > 160 || id != string(run) || status != string(domain.RunSucceeded) || domain.ValidateSHA256Digest("native.history.marker", marker) != nil {
		rows.Close()
		return snapshot, q.budget.deny()
	}
	if decodeOwnedEffectCanonicalJSON(raw, &snapshot.Run) != nil || snapshot.Run.Validate() != nil || snapshot.Run.ID != run || snapshot.Run.TenantID != tenant || snapshot.Run.SessionID != session || snapshot.Run.Status != domain.RunSucceeded || snapshot.Run.FinishedAt == nil || !snapshot.Run.FinishedAt.Equal(snapshot.Run.UpdatedAt) || snapshot.Run.UpdatedAt.After(q.at) {
		return snapshot, q.budget.deny()
	}
	snapshot.Marker = marker
	sessionRaw, err := q.readCanonicalJSON(ctx, "SELECT record FROM sessions WHERE tenant_id = $1 AND session_id = $2", tenant, session)
	if err != nil || decodeOwnedEffectCanonicalJSON(sessionRaw, &snapshot.Session) != nil || snapshot.Session.Validate() != nil || snapshot.Session.ID != session || snapshot.Session.TenantID != tenant || snapshot.Session.LastEventSequence == 0 || snapshot.Session.LastEventSequence > 25 {
		return snapshot, q.budget.deny()
	}
	rows, err = q.QueryContext(ctx, localCompactionEventsSQL, tenant, session, uint64(0), snapshot.Session.LastEventSequence, uint64(26), uint64(8193))
	if err != nil {
		return snapshot, err
	}
	defer rows.Close()
	for rows.Next() {
		var eventRaw string
		n, err := scanOwnedCurrentRow(rows, &eventRaw)
		var event domain.SessionEvent
		if err != nil || q.budget.materialized(q.callback, n) != nil || len(eventRaw) > 8192 || len(snapshot.Events) >= 25 || decodeOwnedEffectCanonicalJSON(eventRaw, &event) != nil || event.Validate() != nil || event.TenantID != tenant || event.SessionID != session || event.RunID == nil || *event.RunID != run || event.Sequence != uint64(len(snapshot.Events)+1) {
			return snapshot, q.budget.deny()
		}
		snapshot.Events = append(snapshot.Events, event)
	}
	if rows.Err() != nil || rows.Close() != nil || uint64(len(snapshot.Events)) != snapshot.Session.LastEventSequence {
		return snapshot, errors.New("native historical canonical range is incomplete")
	}
	return snapshot, nil
}
